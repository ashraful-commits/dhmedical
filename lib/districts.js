export const DISTRICTS = DISTRICT_GROUPS.flatMap((g) => g.districts.map((d) => d.name));

const norm = (s) =>
  String(s || "")
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/[\s\-_]+/g, " ")
    .trim();

export function findDistricts(query) {
  const q = norm(query);
  if (!q) return [];
  return DISTRICT_GROUPS.flatMap((g) =>
    g.districts
      .filter((d) =>
        [d.name, d.en, ...d.aliases, ...d.upazilas.flatMap((u) => [u.name, u.en])].some((v) => norm(v).includes(q))
      )
      .map((d) => ({ ...d, division: g.division }))
  );
}

export function findLocations(query) {
  const q = norm(query);
  if (!q) return [];
  const out = [];
  DISTRICT_GROUPS.forEach((g) => {
    g.districts.forEach((d) => {
      const districtHit = [d.name, d.en, ...d.aliases].some((v) => norm(v).includes(q));
      d.upazilas.forEach((u) => {
        const upazilaHit = [u.name, u.en].some((v) => norm(v).includes(q));
        const villageHits = u.villages.filter((v) => norm(v).includes(q));
        const thanaHits = u.thanas.filter((v) => norm(v).includes(q));
        if (districtHit || upazilaHit || villageHits.length || thanaHits.length) {
          out.push({
            district: d.name,
            districtEn: d.en,
            division: g.division,
            upazila: u.name,
            upazilaEn: u.en,
            thanas: u.thanas,
            villages: u.villages,
            matchedVillages: villageHits,
          });
        }
      });
    });
  });
  return out;
}
