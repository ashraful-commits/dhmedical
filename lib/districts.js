const parseUpazilas = (rows) =>
  rows.map((row) => {
    const [name, en, villages = ""] = row.split("|");
    return {
      name,
      en,
      thanas: [`${name} থানা`, `${en} Thana`],
      villages: villages.split(",").map((v) => v.trim()).filter(Boolean),
    };
  });

const district = (name, en, aliases, rows) => ({
  name,
  en,
  aliases: [name, en, ...aliases],
  upazilas: parseUpazilas(rows),
});

