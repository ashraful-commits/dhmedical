const LanguageContext = createContext({
  lang: "bn",
  setLang: () => {},
  t: (k) => k,
  toggleLang: () => {},
});

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState("bn");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("dh_lang");
      if (saved === "en" || saved === "bn") {
        setLangState(saved);
      }
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem("dh_lang", lang);
    } catch {}
  }, [lang]);

  const setLang = useCallback((newLang) => {
    if (newLang !== "bn" && newLang !== "en") return;
    setLangState(newLang);
  }, []);

  const toggleLang = useCallback(() => {
    setLangState((current) => (current === "bn" ? "en" : "bn"));
  }, []);

  const t = useCallback(
    (key) => translations[lang]?.[key] ?? translations.bn?.[key] ?? key,
    [lang]
  );

  const value = useMemo(
    () => ({ lang, setLang, toggleLang, t }),
    [lang, setLang, toggleLang, t]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      lang: "bn",
      setLang: () => {},
      toggleLang: () => {},
      t: (k) => translations["bn"]?.[k] || k,
    };
  }
  return context;
}
